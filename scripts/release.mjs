#!/usr/bin/env node
// Cut a release: bump every version site in lockstep, roll the changelog,
// commit, and tag. Pushing (and creating the GitHub release that triggers the
// prebuilds workflow) is a separate, explicit step.
//
//   node scripts/release.mjs 0.2.0            bump, commit, tag locally
//   node scripts/release.mjs 0.2.0 --dry-run  show what would change
//   node scripts/release.mjs 0.2.0 --push     also push main + tag and create
//                                             the GitHub release
//
// Version sites kept in sync (all must agree or the npm wrapper cannot resolve
// its platform packages):
//   Cargo.toml                    [workspace.package] version
//   deltafs-fuse/Cargo.toml       [package] version
//   npm/deltabox-lite/package.json  version + the four optionalDependencies
//   Cargo.lock                    regenerated by cargo for the workspace crates

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

// run() throws instead of exiting so callers can roll back first; this turns
// any escaped throw into a one-line "release: ..." message and exit code 1.
process.on("uncaughtException", (error) => fail(error.message));

const args = process.argv.slice(2);
const flags = new Set(args.filter((arg) => arg.startsWith("--")));
const positional = args.filter((arg) => !arg.startsWith("--"));
const dryRun = flags.has("--dry-run");
const push = flags.has("--push");

for (const flag of flags) {
  if (!["--dry-run", "--push"].includes(flag)) fail(`unknown flag ${flag}`);
}
if (positional.length !== 1) fail("usage: node scripts/release.mjs <version> [--dry-run] [--push]");
const version = positional[0];
const tag = `v${version}`;

// Semantic version: MAJOR.MINOR.PATCH with an optional pre-release suffix.
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
  fail(`"${version}" is not a semantic version like 0.2.0 or 0.2.0-rc.1`);
}

const files = {
  workspace: join(root, "Cargo.toml"),
  fuse: join(root, "deltafs-fuse", "Cargo.toml"),
  npm: join(root, "npm", "deltabox-lite", "package.json"),
  lock: join(root, "Cargo.lock"),
  changelog: join(root, "CHANGELOG.md"),
};

// --- preflight ---------------------------------------------------------------

const current = readFileSync(files.workspace, "utf8").match(
  /\[workspace\.package\][\s\S]*?\nversion = "([^"]+)"/,
)?.[1];
if (!current) fail("could not read [workspace.package] version from Cargo.toml");
// The very first release ships the version the tree already carries, so an
// unchanged version is allowed as long as it has not been tagged yet: only
// the changelog rolls in that case.
const bump = current !== version;

if (git("status", "--porcelain").trim() !== "") {
  if (dryRun) console.warn("release: warning: working tree is not clean");
  else fail("working tree is not clean; commit or stash first");
}
if (git("tag", "--list", tag).trim() !== "") fail(`tag ${tag} already exists`);
const branch = git("rev-parse", "--abbrev-ref", "HEAD").trim();
if (push && branch !== "main") {
  fail(`--push releases from main only (currently on ${branch})`);
}

console.log(
  `${dryRun ? "[dry-run] " : ""}release ${bump ? `${current} -> ${version}` : `${version} (version unchanged)`} on ${branch}`,
);

// --- plan every edit in memory first ----------------------------------------
// Nothing touches disk until every transform has succeeded, so a refused
// release (empty changelog, ambiguous version line) leaves the tree untouched.

const plan = [];

if (bump) {
  plan.push(planEdit(files.workspace, (text) =>
    replaceOnce(
      text,
      /(\[workspace\.package\][\s\S]*?\nversion = ")[^"]+(")/,
      `$1${version}$2`,
      "[workspace.package] version",
    ),
  ));

  plan.push(planEdit(files.fuse, (text) =>
    replaceOnce(
      text,
      /(\[package\][\s\S]*?\nversion = ")[^"]+(")/,
      `$1${version}$2`,
      "deltafs-fuse [package] version",
    ),
  ));

  plan.push(planEdit(files.npm, (text) => {
    const manifest = JSON.parse(text);
    manifest.version = version;
    for (const name of Object.keys(manifest.optionalDependencies ?? {})) {
      if (!name.startsWith("deltabox-lite-")) continue;
      manifest.optionalDependencies[name] = version;
    }
    return `${JSON.stringify(manifest, null, 2)}\n`;
  }));
}

plan.push(planEdit(files.changelog, (text) => rollChangelog(text, version)));

if (dryRun) {
  for (const edit of plan) console.log(`[dry-run] would update ${rel(edit.path)}`);
  console.log("[dry-run] no files written, nothing committed");
  process.exit(0);
}

// --- write -------------------------------------------------------------------

const edits = [];
for (const edit of plan) {
  writeFileSync(edit.path, edit.after);
  edits.push(edit.path);
  console.log(`updated ${rel(edit.path)}`);
}

if (bump) {
  // Only the workspace crates change; --offline keeps this from touching the
  // registry so a release never depends on network access. A failure here
  // restores the files written above so the tree does not stay half-bumped.
  try {
    run("cargo", ["update", "--workspace", "--offline"]);
  } catch (error) {
    git("checkout", "--", ...edits);
    throw error;
  }
  edits.push(files.lock);
}

// --- verify ------------------------------------------------------------------

if (bump) {
  const lock = readFileSync(files.lock, "utf8");
  for (const crate of ["deltabox", "deltabox-core", "deltabox-node", "deltafs-fuse"]) {
    const entry = lock.match(new RegExp(`\\[\\[package\\]\\]\\nname = "${crate}"\\nversion = "([^"]+)"`));
    if (entry?.[1] !== version) {
      fail(`Cargo.lock still lists ${crate} at ${entry?.[1] ?? "?"}; expected ${version}`);
    }
  }
}

// --- commit + tag ------------------------------------------------------------

// The tag annotation carries the changelog section, so the GitHub release can
// take its notes straight from the tag (`gh release create --notes-from-tag`).
const notes = changelogSection(readFileSync(files.changelog, "utf8"), version);
git("add", "--", ...edits);
git("commit", "--quiet", "--message", `release: ${tag}`);
git("tag", "--annotate", tag, "--message", `deltabox-lite ${tag}\n\n${notes}`);
console.log(`committed and tagged ${tag}`);

if (!push) {
  console.log(`
next steps (review first, then):
  git push origin ${branch} ${tag}
  gh release create ${tag} --title "${tag}" --notes-from-tag
or rerun with --push to do both. Publishing the release triggers the
prebuilds workflow, which builds all platforms and publishes to npm.`);
  process.exit(0);
}

git("push", "origin", branch, tag);
run("gh", ["release", "create", tag, "--title", tag, "--notes-from-tag"]);
console.log(`pushed ${tag} and created the GitHub release; the prebuilds workflow will publish from it`);

// --- helpers -----------------------------------------------------------------

function planEdit(path, transform) {
  const before = existsSync(path) ? readFileSync(path, "utf8") : "";
  const after = transform(before);
  if (after === before) fail(`${rel(path)}: nothing to change`);
  return { path, after };
}

function replaceOnce(text, pattern, replacement, what) {
  const matches = text.match(new RegExp(pattern.source, "g")) ?? [];
  if (matches.length !== 1) {
    fail(`expected exactly one ${what}, found ${matches.length}`);
  }
  return text.replace(pattern, replacement);
}

// Keep a Changelog layout: whatever sits under "## [Unreleased]" becomes the
// new version's section, and a fresh empty Unreleased heading goes on top.
function rollChangelog(text, version) {
  const today = new Date().toISOString().slice(0, 10);
  if (text === "") {
    return `# Changelog

All notable changes to this project are documented in this file. The format
follows [Keep a Changelog](https://keepachangelog.com/en/1.1.0/), and the
project uses [Semantic Versioning](https://semver.org/).

## [Unreleased]

## [${version}] - ${today}

- Initial release.
`;
  }
  const marker = "## [Unreleased]";
  const start = text.indexOf(marker);
  if (start === -1) fail("CHANGELOG.md has no '## [Unreleased]' section");
  const bodyStart = start + marker.length;
  const nextHeading = text.indexOf("\n## [", bodyStart);
  const bodyEnd = nextHeading === -1 ? text.length : nextHeading;
  const body = text.slice(bodyStart, bodyEnd).replace(/^\s+|\s+$/g, "");
  if (body === "") fail("CHANGELOG.md: the Unreleased section is empty; describe the release first");
  const head = text.slice(0, start);
  const tail = text.slice(bodyEnd).replace(/^\n+/, "");
  return `${head}${marker}\n\n## [${version}] - ${today}\n\n${body}\n${tail ? `\n${tail}` : ""}`;
}

function changelogSection(text, version) {
  const heading = `## [${version}]`;
  const start = text.indexOf(heading);
  if (start === -1) return `deltabox-lite ${version}`;
  const bodyStart = text.indexOf("\n", start) + 1;
  const next = text.indexOf("\n## [", bodyStart);
  return text.slice(bodyStart, next === -1 ? text.length : next).trim();
}

function git(...argv) {
  return run("git", argv);
}

// Throws rather than exiting so callers can roll back before the process
// dies; the uncaughtException handler below turns the throw into a clean
// "release: ..." message and exit code 1.
function run(command, argv) {
  try {
    return execFileSync(command, argv, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });
  } catch (error) {
    if (error.code === "ENOENT") throw new Error(`${command} is not on PATH`);
    throw new Error(`${command} ${argv.join(" ")} failed`);
  }
}

function rel(path) {
  return relative(root, path);
}

function fail(message) {
  console.error(`release: ${message}`);
  process.exit(1);
}
