#!/usr/bin/env node
// Cut a release: bump every version site in lockstep, roll the changelog,
// commit, and tag. Pushing is a separate, explicit step; the tag push is what
// triggers the prebuilds workflow, which builds every platform, publishes to
// npm, and turns the draft GitHub release into a public one only after all of
// that succeeded.
//
//   node scripts/release.mjs 0.2.0            bump, commit, tag locally
//   node scripts/release.mjs 0.2.0 --dry-run  show what would change
//   node scripts/release.mjs 0.2.0 --push     also push main + tag atomically
//
// Version sites kept in sync (all must agree or the npm wrapper cannot resolve
// its platform packages):
//   Cargo.toml                    [workspace.package] version
//   deltafs-fuse/Cargo.toml       [package] version
//   npm/deltabox-lite/package.json  version + the platform optionalDependencies
//   Cargo.lock                    regenerated by cargo for the workspace crates

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

// run() throws instead of exiting so callers can roll back first; this turns
// any escaped throw into a one-line "release: ..." message and exit code 1.
process.on("uncaughtException", (error) => fail(error.message));

const args = process.argv.slice(2);
const flags = new Set(args.filter((arg) => arg.startsWith("--")));
const positional = args.filter((arg) => !arg.startsWith("--"));
const dryRun = flags.has("--dry-run");
const push = flags.has("--push");

for (const flag of flags) {
  if (!["--dry-run", "--push"].includes(flag)) fail(`unknown flag ${flag}`);
}
if (positional.length !== 1) fail("usage: node scripts/release.mjs <version> [--dry-run] [--push]");
const version = positional[0];
const tag = `v${version}`;

// Semantic version: MAJOR.MINOR.PATCH with an optional pre-release suffix.
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
  fail(`"${version}" is not a semantic version like 0.2.0 or 0.2.0-rc.1`);
}

const files = {
  workspace: join(root, "Cargo.toml"),
  fuse: join(root, "deltafs-fuse", "Cargo.toml"),
  npm: join(root, "npm", "deltabox-lite", "package.json"),
  lock: join(root, "Cargo.lock"),
  changelog: join(root, "CHANGELOG.md"),
};
const WORKSPACE_VERSION = /(\[workspace\.package\][\s\S]*?\nversion = ")([^"]+)(")/;
const FUSE_VERSION = /(\[package\][\s\S]*?\nversion = ")([^"]+)(")/;
const WORKSPACE_CRATES = ["deltabox", "deltabox-core", "deltabox-node", "deltafs-fuse"];

// --- preflight ---------------------------------------------------------------

const current = readFileSync(files.workspace, "utf8").match(WORKSPACE_VERSION)?.[2];
if (!current) fail("could not read [workspace.package] version from Cargo.toml");
// The very first release ships the version the tree already carries, so an
// unchanged version is allowed as long as it has not been tagged yet: only
// the changelog rolls in that case, and every other version site must
// already agree (checked below) — the lockstep guarantee is unconditional.
const bump = current !== version;

if (git("status", "--porcelain").trim() !== "") {
  if (dryRun) console.warn("release: warning: working tree is not clean");
  else fail("working tree is not clean; commit or stash first");
}
if (git("tag", "--list", tag).trim() !== "") fail(`tag ${tag} already exists`);
const branch = git("rev-parse", "--abbrev-ref", "HEAD").trim();
if (push) {
  if (branch !== "main") fail(`--push releases from main only (currently on ${branch})`);
  // Refuse to build a release commit on a stale main: the atomic push would
  // be rejected anyway, but only after the commit and tag exist locally.
  git("fetch", "--quiet", "origin", "main");
  const behind = git("rev-list", "--count", "HEAD..origin/main").trim();
  if (behind !== "0") fail(`local main is ${behind} commit(s) behind origin/main; pull first`);
}

if (!bump) {
  const drift = [];
  const fuse = readFileSync(files.fuse, "utf8").match(FUSE_VERSION)?.[2];
  if (fuse !== version) drift.push(`deltafs-fuse/Cargo.toml has ${fuse ?? "?"}`);
  const manifest = JSON.parse(readFileSync(files.npm, "utf8"));
  if (manifest.version !== version) drift.push(`npm/deltabox-lite/package.json has ${manifest.version}`);
  for (const [name, pin] of Object.entries(manifest.optionalDependencies ?? {})) {
    if (name.startsWith("deltabox-lite-") && pin !== version) drift.push(`npm pin ${name} is ${pin}`);
  }
  const lock = readFileSync(files.lock, "utf8");
  for (const crate of WORKSPACE_CRATES) {
    const found = lockVersion(lock, crate);
    if (found !== version) drift.push(`Cargo.lock lists ${crate} at ${found ?? "?"}`);
  }
  if (drift.length) fail(`version sites disagree with ${version}:\n  ${drift.join("\n  ")}`);
}

console.log(
  `${dryRun ? "[dry-run] " : ""}release ${bump ? `${current} -> ${version}` : `${version} (version unchanged)`} on ${branch}`,
);

// --- plan every edit in memory first ----------------------------------------
// Nothing touches disk until every transform has succeeded, so a refused
// release (empty changelog, ambiguous version line) leaves the tree untouched.

const plan = [];

if (bump) {
  plan.push(planEdit(files.workspace, (text) =>
    replaceOnce(text, WORKSPACE_VERSION, (_, open, __, close) => `${open}${version}${close}`, "[workspace.package] version"),
  ));
  plan.push(planEdit(files.fuse, (text) =>
    replaceOnce(text, FUSE_VERSION, (_, open, __, close) => `${open}${version}${close}`, "deltafs-fuse [package] version"),
  ));
  plan.push(planEdit(files.npm, (text) => {
    const manifest = JSON.parse(text);
    manifest.version = version;
    for (const name of Object.keys(manifest.optionalDependencies ?? {})) {
      if (!name.startsWith("deltabox-lite-")) continue;
      manifest.optionalDependencies[name] = version;
    }
    return `${JSON.stringify(manifest, null, 2)}\n`;
  }));
}

plan.push(planEdit(files.changelog, (text) => rollChangelog(text, version)));

if (dryRun) {
  for (const edit of plan) console.log(`[dry-run] would update ${rel(edit.path)}`);
  console.log("[dry-run] no files written, nothing committed");
  process.exit(0);
}

// --- write, then everything after this point rolls back on failure ----------

const edits = [];
let committed = false;
try {
  for (const edit of plan) {
    writeFileSync(edit.path, edit.after);
    edits.push(edit.path);
    console.log(`updated ${rel(edit.path)}`);
  }

  if (bump) {
    // Only the workspace crates change. Prefer --offline so a release never
    // needs the network, but a machine without a warm registry cache cannot
    // resolve even a no-op update offline, so fall back to an online run.
    edits.push(files.lock);
    try {
      run("cargo", ["update", "--workspace", "--offline"]);
    } catch (offlineError) {
      console.warn(`release: ${offlineError.message}; retrying online`);
      run("cargo", ["update", "--workspace"]);
    }
    const lock = readFileSync(files.lock, "utf8");
    for (const crate of WORKSPACE_CRATES) {
      const found = lockVersion(lock, crate);
      if (found !== version) throw new Error(`Cargo.lock still lists ${crate} at ${found ?? "?"}; expected ${version}`);
    }
  }

  // The tag annotation's subject names the release; its body is the
  // changelog section, which the prebuilds workflow uses as the GitHub
  // release notes (`git tag -l --format='%(contents:body)'`).
  const notes = changelogSection(readFileSync(files.changelog, "utf8"), version);
  git("add", "--", ...edits);
  git("commit", "--quiet", "--message", `release: ${tag}`);
  committed = true;
  // --cleanup=verbatim: git would otherwise strip the "### Added" style
  // markdown headings as comment lines.
  git("tag", "--annotate", "--cleanup=verbatim", tag, "--message", `deltabox-lite ${tag}\n\n${notes}`);
  console.log(`committed and tagged ${tag}`);
} catch (error) {
  rollback(error);
}

if (!push) {
  console.log(`
next steps (review the commit and tag first, then):
  git push --atomic origin ${branch} ${tag}
or rerun with --push. The tag push triggers the prebuilds workflow, which
builds every platform, publishes to npm, and then publishes the GitHub
release (created as a draft from the tag message).`);
  process.exit(0);
}

// --atomic: either both refs land or neither does, so a rejected main can
// never leave a stray release tag on origin.
git("push", "--atomic", "origin", branch, tag);
console.log(`pushed ${branch} and ${tag}; the prebuilds workflow will build, publish to npm, and publish the release`);

// --- helpers -----------------------------------------------------------------

function planEdit(path, transform) {
  const existed = existsSync(path);
  const before = existed ? readFileSync(path, "utf8") : "";
  const after = transform(before);
  if (after === before) fail(`${rel(path)}: nothing to change`);
  return { path, after, existed };
}

// Put the tree back exactly as it was before the write phase, whatever step
// failed: unstage and restore every written file (deleting ones that did not
// exist before), drop the release commit if it was made, and drop the tag if
// it was created. Then surface the original error.
function rollback(error) {
  console.error(`release: ${error.message}; rolling back`);
  const restoreErrors = [];
  const attempt = (label, thunk) => {
    try {
      thunk();
    } catch (e) {
      restoreErrors.push(`${label}: ${e.message}`);
    }
  };
  if (git("tag", "--list", tag).trim() !== "") attempt("delete tag", () => git("tag", "--delete", tag));
  if (committed) attempt("drop release commit", () => git("reset", "--quiet", "--soft", "HEAD~1"));
  attempt("unstage", () => git("reset", "--quiet", "--", ...edits));
  for (const edit of plan) {
    if (edit.existed) attempt(`restore ${rel(edit.path)}`, () => git("checkout", "--", edit.path));
    else attempt(`remove ${rel(edit.path)}`, () => rmSync(edit.path, { force: true }));
  }
  if (edits.includes(files.lock)) attempt("restore Cargo.lock", () => git("checkout", "--", files.lock));
  if (restoreErrors.length) {
    console.error(`release: rollback was incomplete, check \`git status\`:\n  ${restoreErrors.join("\n  ")}`);
  }
  fail(error.message);
}

function replaceOnce(text, pattern, replacer, what) {
  const matches = text.match(new RegExp(pattern.source, `${pattern.flags}g`)) ?? [];
  if (matches.length !== 1) {
    fail(`expected exactly one ${what}, found ${matches.length}`);
  }
  // A replacer function inserts its result literally; a replacement string
  // would expand `$` sequences in the version.
  return text.replace(pattern, replacer);
}

function lockVersion(lock, crate) {
  return lock.match(new RegExp(`\\[\\[package\\]\\]\\nname = "${crate}"\\nversion = "([^"]+)"`))?.[1];
}

// Keep a Changelog layout: whatever sits under "## [Unreleased]" becomes the
// new version's section, and a fresh empty Unreleased heading goes on top.
// Headings are matched at line start and fenced code blocks are skipped, so a
// "## [" inside an example cannot be mistaken for the next section.
function rollChangelog(text, version) {
  const today = new Date().toISOString().slice(0, 10);
  if (text === "") {
    return `# Changelog

All notable changes to this project are documented in this file. The format
follows [Keep a Changelog](https://keepachangelog.com/en/1.1.0/), and the
project uses [Semantic Versioning](https://semver.org/).

## [Unreleased]

## [${version}] - ${today}

- Initial release.
`;
  }
  const lines = text.split("\n");
  const headings = sectionHeadings(lines);
  const unreleased = headings.find((h) => /^## \[Unreleased\]/i.test(lines[h]));
  if (unreleased === undefined) fail("CHANGELOG.md has no '## [Unreleased]' section");
  const next = headings.find((h) => h > unreleased);
  const bodyEnd = next ?? lines.length;
  const body = lines.slice(unreleased + 1, bodyEnd).join("\n").replace(/^\s+|\s+$/g, "");
  if (body === "") fail("CHANGELOG.md: the Unreleased section is empty; describe the release first");
  const head = lines.slice(0, unreleased).join("\n");
  const tail = lines.slice(bodyEnd).join("\n").replace(/^\n+/, "");
  return `${head}\n## [Unreleased]\n\n## [${version}] - ${today}\n\n${body}\n${tail ? `\n${tail}` : ""}`;
}

// Line numbers of every "## [" section heading outside fenced code blocks.
function sectionHeadings(lines) {
  const result = [];
  let fenced = false;
  lines.forEach((line, index) => {
    if (/^\s*(```|~~~)/.test(line)) {
      fenced = !fenced;
      return;
    }
    if (!fenced && /^## \[/.test(line)) result.push(index);
  });
  return result;
}

function changelogSection(text, version) {
  const lines = text.split("\n");
  const headings = sectionHeadings(lines);
  const start = headings.find((h) => lines[h].startsWith(`## [${version}]`));
  if (start === undefined) return `deltabox-lite ${version}`;
  const next = headings.find((h) => h > start);
  return lines.slice(start + 1, next ?? lines.length).join("\n").trim();
}

function git(...argv) {
  return run("git", argv);
}

// Throws rather than exiting so callers can roll back before the process
// dies; the uncaughtException handler above turns the throw into a clean
// "release: ..." message and exit code 1.
function run(command, argv) {
  try {
    return execFileSync(command, argv, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });
  } catch (error) {
    if (error.code === "ENOENT") throw new Error(`${command} is not on PATH`);
    throw new Error(`${command} ${argv.join(" ")} failed`);
  }
}

function rel(path) {
  return relative(root, path);
}

function fail(message) {
  console.error(`release: ${message}`);
  process.exit(1);
}
